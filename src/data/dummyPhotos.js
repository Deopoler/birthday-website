const colors = ['#f9c6d0', '#c6e2f9', '#d4f0c0', '#fde9a9', '#e0cdf5', '#ffd5b0']
const sizes = [
  [900, 1200],  // 세로 3:4
  [1200, 900],  // 가로 4:3
  [1000, 1000], // 정사각 1:1
  [900, 1200],  // 세로 3:4
  [1200, 675],  // 파노라마 16:9
  [675, 1200],  // 긴 세로 9:16
  [1200, 900],  // 가로 4:3
  [900, 1200],  // 세로 3:4
  [1000, 1000], // 정사각 1:1
  [1200, 800],  // 가로 3:2
  [800, 1200],  // 세로 2:3
  [1200, 900],  // 가로 4:3
]

export const dummyPhotos = sizes.map(([width, height], i) => ({
  id: i,
  src: null,
  thumb: null,
  width,
  height,
  color: colors[i % colors.length],
}))
