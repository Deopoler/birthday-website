// 사진 폴더(photos/)가 비어 있을 때 대신 보여 주는 더미 목록.
// 세로(3:4, 2:3, 9:16), 가로(4:3, 3:2, 16:9), 정사각(1:1) 등 다양한 비율을 섞어
// 포스트잇이 사진 비율에 맞춰 자연스럽게 달라지는 모습을 보여 준다.
const COLORS = ['#f9c6d0', '#c6e2f9', '#d4f0c0', '#fde9a9', '#e0cdf5', '#ffd5b0']

const SIZES = [
  [900, 1200],  // 0: 세로 3:4
  [1200, 900],  // 1: 가로 4:3
  [1000, 1000], // 2: 정사각 1:1
  [675, 1200],  // 3: 긴 세로 9:16
  [1200, 675],  // 4: 파노라마 16:9
  [900, 1200],  // 5: 세로 3:4
  [1200, 800],  // 6: 가로 3:2
  [800, 1200],  // 7: 세로 2:3
  [1000, 1000], // 8: 정사각 1:1
  [1200, 900],  // 9: 가로 4:3
  [675, 1200],  // 10: 긴 세로 9:16
  [1200, 675],  // 11: 파노라마 16:9
]

export const dummyPhotos = SIZES.map(([width, height], i) => ({
  id: i,
  src: null,
  thumb: null,
  width,
  height,
  color: COLORS[i % COLORS.length],
}))
