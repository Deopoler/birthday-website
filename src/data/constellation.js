// 별자리 좌표 (정규화 0~1, x: 가로, y: 세로). 세로 화면에 '이하진'이 세 줄로 읽히도록 배치.
export const CONSTELLATION_TEXT = '이하진'

// 세로 화면 비율(가로/세로) 보정: 원이 찌그러지지 않도록 y 반지름을 줄인다.
const ASPECT = 0.55
const ring = (cx, cy, r, n, start = 0) =>
  Array.from({ length: n }, (_, i) => {
    const a = start + (i / n) * Math.PI * 2
    return [cx + r * Math.cos(a), cy + r * ASPECT * Math.sin(a)]
  })

// 이 (9): ㅇ 6 + ㅣ 3
const I = [...ring(0.36, 0.2, 0.12, 6), [0.74, 0.1], [0.74, 0.2], [0.74, 0.3]]
// 하 (11): ㅎ(꼭지 1 + 가로획 2 + 원 4) + ㅏ(세로 3 + 짧은 획 1)
const HA = [
  [0.36, 0.385],
  [0.2, 0.425],
  [0.52, 0.425],
  ...ring(0.36, 0.52, 0.1, 4, Math.PI / 2),
  [0.74, 0.4],
  [0.74, 0.49],
  [0.74, 0.58],
  [0.86, 0.49],
]
// 진 (10): ㅈ(위 가로획 2 + 가운데 1 + 다리 2) + ㅣ 2 + ㄴ 3
const JIN = [
  [0.14, 0.65],
  [0.4, 0.65],
  [0.27, 0.7],
  [0.14, 0.82],
  [0.4, 0.82],
  [0.62, 0.64],
  [0.62, 0.8],
  [0.5, 0.84],
  [0.5, 0.92],
  [0.84, 0.92],
]

export const constellation = [...I, ...HA, ...JIN].map(([x, y]) => ({
  x: +x.toFixed(3),
  y: +y.toFixed(3),
}))
